// Writes the agent skill's reference files from the docs data, so the
// catalogue in skills/fancyborders never drifts from the site. SKILL.md
// itself is written by hand. Run with `bun run skill:build`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

import { CATEGORIES, COMPONENTS } from "../src/content/docs.ts";
import { PROPERTIES, SCOPE, UTILITIES, VARIANTS } from "../src/content/theming.ts";

// The skill is committed, so it always points at the public site.
const site = (process.env.NEXT_PUBLIC_SITE_URL ?? "https://fancyborders.vercel.app").replace(/\/$/, "");
const dir = "skills/fancyborders/references";
const items = JSON.parse(readFileSync("registry/items.json", "utf8"));
const byName = Object.fromEntries(items.map((item) => [item.name, item]));

const table = (head, rows) =>
  [
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map((cell) => String(cell).replace(/\|/g, "\\|")).join(" | ")} |`),
  ].join("\n");

const header = (title) =>
  `<!-- Generated by scripts/build-skill.mjs from src/content. Do not edit by hand. -->\n\n# ${title}`;

const components = [
  header("Components"),
  `Every component, by category. Install the **item** with \`npx shadcn@latest add ${site}/r/<item>.json\` (or \`@fancyborders/<item>\` with the registry namespace). A **recipe** has no item of its own: install the item it names and copy the code from its docs. Full docs for any component, as Markdown: \`${site}/docs/components/<slug>.md\`.`,
  ...CATEGORIES.map((category) =>
    [
      `## ${category.title}`,
      category.lead,
      table(
        ["Component", "Slug", "Item", "Exports", "What it is"],
        COMPONENTS.filter((doc) => doc.category === category.id).map((doc) => [
          doc.title,
          `\`${doc.slug}\``,
          `\`${doc.item}\`${doc.recipe ? " (recipe)" : ""}`,
          doc.api.map((name) => `\`${name}\``).join(", "),
          doc.description,
        ]),
      ),
    ].join("\n\n"),
  ),
  "## Registry items",
  table(
    ["Item", "Built on", "What it is"],
    items.map((item) => [
      `\`${item.name}\``,
      item.requires?.map((name) => `\`${name}\``).join(", ") ?? "–",
      item.description,
    ]),
  ),
  `Client components (they need the browser): ${["frame-spotlight", "frame-metal", "edge-frame"]
    .filter((name) => byName[name])
    .map((name) => `\`${name}\``)
    .join(", ")}. Everything else renders on the server.`,
].join("\n\n");

const theming = [
  header("Theming"),
  "Frames read their colours and sizes from custom properties, and each one has a Tailwind utility. Colour utilities take theme colours, arbitrary values and opacity modifiers (`frame-color-sky-500/50`).",
  table(["Utility", "Sets"], UTILITIES.map(([name, sets]) => [`\`${name}\``, sets])),
  "They are ordinary utilities, so every variant works:",
  "```tsx\n" + VARIANTS + "\n```",
  "The properties inherit, so a utility on an ancestor themes every frame beneath it:",
  "```tsx\n" + SCOPE + "\n```",
  "The custom properties behind them, to set in CSS or a style attribute:",
  table(["Property", "Sets"], PROPERTIES.map(([name, sets]) => [`\`${name}\``, sets])),
].join("\n\n");

mkdirSync(dir, { recursive: true });
writeFileSync(`${dir}/components.md`, `${components}\n`);
writeFileSync(`${dir}/theming.md`, `${theming}\n`);
console.log(`skill references: ${COMPONENTS.length} components, ${items.length} items, for ${site}`);
